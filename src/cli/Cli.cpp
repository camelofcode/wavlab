#include <filesystem>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <string_view>

namespace
{

void renderCommand(std::ostringstream &markdown, const CLI::App &command,
                   const std::string &invocation)
{
    markdown << "\n## `" << invocation << "`\n\n```text\n";
    const auto separator = invocation.rfind(' ');
    const auto prefix =
        separator == std::string::npos ? std::string{} : invocation.substr(0, separator);
    const auto help = command.help(prefix, CLI::AppFormatMode::Normal);
    markdown << help;
    if (!help.ends_with('\n'))
    {
        markdown << '\n';
    }
    markdown << "```\n";

    for (const auto *subcommand : command.get_subcommands([](const CLI::App *) { return true; }))
    {
        if (subcommand->get_name() == "_generate-cli-docs")
        {
            continue;
        }
        renderCommand(markdown, *subcommand, invocation + " " + subcommand->get_name());
    }
}

} // namespace

CommandLine::CommandLine() : app_("Inspect and process PCM WAV files", "wavlab")
{
    app_.set_version_flag("-V,--version", WAVLAB_VERSION);
    app_.require_subcommand(1);
    app_.footer("Run 'wavlab COMMAND --help' for detailed command usage.");

    configureGeneratorCommands(app_, selectedAction_);
    configureToolCommands(app_, selectedAction_);
    configureEqCommands(app_, selectedAction_);
    configureEffectCommands(app_, selectedAction_);

    struct DocsArguments
    {
        std::filesystem::path output{"-"};
    };
    addCommand<DocsArguments>(
        app_, selectedAction_, "_generate-cli-docs", "Generate the checked-in CLI reference",
        [](CLI::App &command, DocsArguments &arguments)
        {
            command.group("");
            command.add_option("OUTPUT", arguments.output, "Output path, or - for stdout");
        },
        [](const DocsArguments &arguments)
        {
            // Parsing marks the generator subcommand as selected, so render a
            // fresh definition tree rather than leaking that state into help.
            const CommandLine referenceCommandLine;
            const auto reference = referenceCommandLine.referenceMarkdown();
            if (arguments.output == "-")
            {
                std::cout << reference;
                return;
            }
            std::ofstream output(arguments.output);
            if (!output)
            {
                throw std::runtime_error("could not open CLI reference output");
            }
            output << reference;
        });
}

void CommandLine::parse(int argc, char *argv[]) { app_.parse(argc, argv); }

void CommandLine::execute()
{
    if (!selectedAction_)
    {
        throw std::logic_error("no CLI action was selected");
    }
    selectedAction_();
}

int CommandLine::exit(const CLI::ParseError &error) const { return app_.exit(error); }

std::string CommandLine::referenceMarkdown() const
{
    std::ostringstream markdown;
    markdown << "<!-- This file is generated by `wavlab _generate-cli-docs`. -->\n"
                "<!-- Do not edit it manually; update the definitions in `src/cli`. -->\n\n"
                "# Command-line reference\n\n"
                "This reference is generated from the same CLI11 definitions used by the "
                "`wavlab` executable.\n";
    renderCommand(markdown, app_, "wavlab");
    return markdown.str();
}
